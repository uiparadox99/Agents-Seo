            <h2 style="font-weight: bold">Government lists 'salient features' of 2019 Hajj policy</h2>
            <p><strong>Issue Date : </strong> 12/2/2019</p>
            <img src="{{ url('images/hajj.jpg') }}" style="width: 100%;margin-bottom: 10px;" alt="Government lists 'salient features' of 2019 Hajj policy">
            <br>


            <p>ISLAMABAD: The government of Pakistan has highlighted the salient features of its latest Hajj policy, for
                the year 2019, a memo released on Monday read.</p>

            <p>Issued by the Ministry of Religious Affairs, the document lists 27 important features of the Hajj Policy
                2019. They are as follows:</p>

            <p>1. Hajj quota allocated to Pakistan is 179,210 + 5,000.</p>

            <p>2. Government Hajj Scheme 2019 shall be implemented through the government and private Hajj Group
                Organizers (HGOs) with a 60:40 ratio.</p>

            <p>3. The additional quota of 5,000 will be allotted to newly-enrolled, non-quota-holding companies.</p>

            <p>4. There shall be no free Hajj.</p>

            <p>5. The Hajj dues for Hajj 2019 under the Government Hajj Scheme will be Rs436,975 and Rs426,975 for North
                (which includes Islamabad, Lahore, Peshawar, Sialkot, Faisalabad, Multan, and Rahim Yar Khan) and South
                (which comprises Karachi, Quetta, and Sukkur), respectively. Qurbani charges will be Rs19,451
                (optional).</p>

            <p>6. Hajj dues for infants (born after 15-09-2017 (or September 15, 2017)) under Government Hajj Scheme
                will be Rs12,910 and Rs11,910 for North and South, respectively.</p>

            <p>7. International Machine Readable Pakistani Passport (IMRPP) valid up to 10-02-2020 (or February 2, 2020)
                and a valid CNIC will be required for submission of the Hajj application in the banks.</p>

            <p>8. Applications under the Government Hajj Scheme will be received in fourteen (14) designated banks
                &mdash; which include Habib Bank Limited, United Bank Limited, National Bank of Pakistan, MCB Bank
                Limited, Allied Bank Limited, Bank of Punjab, Meezan Bank, Bank Al-Falah, Bank Al-Habib, Zarai Taraqiati
                Bank, Faysal Bank, Habibmetro Bank Limited, Askari Bank, and Dubai Islamic Bank &mdash; from February 25
                to March 6, and balloting will be held on March 8, 2019.</p>

            <p>9. Hajj dues will be deposited in Shariah-compliant accounts/instruments by the designated banks.</p>

            <p>10. The selection of Hujjaj of the Government Hajj Scheme will be made through computerized balloting.
            </p>

            <p>11. In total, 10,000 seats would be reserved for senior citizens (above the age of 80 years). Female
                pilgrims above the age of 80 years may be accompanied by female helpers along with their joint mehram
                while male aged pilgrims may be accompanied by one helper.</p>

            <p>12. In total, 10,000 seats would be reserved for persons who have been unsuccessful in ballot
                continuously for the last three years, i.e 2016, 2017, and 2018.</p>

            <p>13. 1.5% of the total seats under Government Hajj Scheme will be reserved for hardship cases.</p>

            <p>14. 500 seats will be reserved for labour/low-paid employees of companies registered with the Employees
                Old-age Benefits Institution (EOBI) and the Workers Welfare Fund (WWF), sponsored by their respective
                organizations under their Corporate Social Responsibility.</p>

            <p>15. Those applicants, including Hajj-e-Badal/Nafal Hajj, would be entertained who have not performed Hajj
                under the Government Hajj Scheme for the last five years i.e. from 2014 and onward. This restriction
                will not apply to mehram of a lady and those who want to avail the private Hajj scheme.</p>

            <p>16. It would be mandatory for a female pilgrim of any age to be accompanied by a mehram. However, in the
                case of Fiqah Jafria female pilgrim above the age of 45 years, a mandatory condition of mehram shall be
                implemented in the light of the Saudi taleemat.</p>

            <p>17. Hujjaj Mohafiz Scheme based on the concept of &quot;Takaful&quot; will continue in Hajj Policy 2019.
            </p>

            <p>18. A comprehensive awareness and training campaign will be launched for Hujjaj and welfare staff.</p>

            <p>19. Each HGO is required to submit performance guarantee at 5% and 10% of packages (package x quota) for
                old and new HGOs, respectively, in the form of bank/cash guarantee, which will be released on
                satisfactory performance.</p>

            <p>20. Monitoring and supervision mechanism for Hajj operation of both Government and Private Schemes will
                be ensured.</p>

            <p>21. To facilitate Hujjaj, the Hajj Medical Mission, Moavineen-i-Hujjaj, Seasonal staff of MORA and IH,
                and KSA-based Moavineen-i-Hujjaj will be deputed as per requirement in KSA [the Kingdom of Saudi Arabia]
                for Hajj 2019.</p>

            <p>22. All the Hujjaj will be provided five (5) litres of ZamZam water.</p>

            <p>23. Some new initiatives are under process to be introduced for Hajj 2019, i.e., launching of &quot;Road
                to Makkah&quot; project at JIA [Jinnah International Airport], Karachi.</p>

            <p>24. Negotiations are underway with KSA authorities for the introduction of E-Visa facility to the Hujjaj
                for Hajj 2019 to meet the international standards.</p>

            <p>25. Temporary Haji Camp will be established in Gilgit and Hujjaj from Gilgit to Islamabad Airport will be
                transported through buses on government expense.</p>

            <p>26. Hujjaj from the Quetta POD will be airlifted directly to KSA.</p>

            <p>27. Biometric verification arrangements will be made in the far-flung districts of Skardu, Turbot,
                Khuzdar, Chitral, and Muzaffarabad.</p>
